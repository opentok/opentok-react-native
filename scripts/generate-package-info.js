#!/usr/bin/env node

const fs = require('node:fs');
const path = require('node:path');

const rootDir = path.resolve(__dirname, '..');
const packageJsonPath = path.join(rootDir, 'package.json');
const generatedDir = path.join(rootDir, 'src', 'generated');
const generatedFilePath = path.join(generatedDir, 'packageInfo.js');

const packageJson = JSON.parse(fs.readFileSync(packageJsonPath, 'utf8'));
const packageInfo = {
  version: packageJson.version,
  repositoryUrl: packageJson.repository?.url || '',
};

const fileContents = `/* eslint-disable */\n// This file is auto-generated by scripts/generate-package-info.js\n// Do not edit manually.\n\nexport const OTRN_PACKAGE_INFO = ${JSON.stringify(packageInfo, null, 2)};\n`;

fs.mkdirSync(generatedDir, { recursive: true });
fs.writeFileSync(generatedFilePath, fileContents);
